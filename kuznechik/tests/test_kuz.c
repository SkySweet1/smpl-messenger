static u8 round_keys[10][16];

u8 mul_gf256(u8 a, u8 b){
    u8 result = 0;

    for(int i = 0; i < 8; i++){
        if (b & 1) {
            result ^= a;
        }
        
        b >>= 1;

        if (a & 0x80){
            a = (a << 1) ^ 0xC3;
        } else {
            a <<= 1;
        }
    }

    return result;
}

void R(u8 *state, const u8 *key){
    u8 tmp[16];

    for(int i = 0; i < 16; i++){
        u8 val = state[i] ^ key[i];
        tmp[i] = Pi[val];
    }

    for(int i = 0; i < 16; i++){
        state[i] = tmp[(i * 9 + 1) % 16];
    }
}

void R_inv(u8 *state, const u8 *key){
    u8 tmp[16];

    for(int i = 0; i < 16; i++){
        int j = (i * 9 + 1) % 16;
        tmp[j] = state[i];
    }

    for(int i = 0; i < 16; i++){
        state[i] = Pi_inv[tmp[i]] ^ key[i];
    }
}

void kuznechik_init(const u8 *master_key){
    memcpy(round_keys[0], master_key, 16);
    memcpy(round_keys[1], master_key + 16, 16);

    for(int i = 2; i < 10; i++){
        u8 iter_const[16] = {0};
        iter_const[0] = i - 1;

        u8 temp[16];
        memcpy(temp, round_keys[i-1], 16);

        for(int j = 0; j < 16; j++) temp[j] ^= iter_const[j];

        R(temp, round_keys[i-2]);
        memcpy(round_keys[i], temp, 16);
    }
}

void kuznechik_encrypt(const u8 *plain, u8 *cipher){
    memcpy(cipher, plain, 16);

    for(int i = 0; i < 9; i++){
        R(cipher, round_keys[i]);
    }

    for(int i = 0; i < 16; i++){
        cipher[i] = Pi[cipher[i] ^ round_keys[9][i]];
    }
}

void kuznechik_decrypt(const u8 *cipher, u8 *plain){
    memcpy(plain, cipher, 16);

    for(int i = 0; i < 16; i++){
        plain[i] = Pi_inv[plain[i]] ^ round_keys[9][i];
    }

    for(int i = 8; i >= 0; i--){
        R_inv(plain, round_keys[i]);
    }
}

void encrypt_message(const char *msg, u8 *encrypted, size_t *enc_len){
    size_t msg_len = strlen(msg);
    u8 padded[1024];
    size_t padded_len = msg_len;

    memcpy(padded, msg, msg_len);

    size_t pad_len = 16 - (msg_len % 16);

    if(pad_len == 16){
        pad_len = 0;
    }

    if(pad_len > 0){
        memset(padded + msg_len, pad_len, pad_len);
        padded_len = msg_len + pad_len;
    }

    *enc_len = padded_len;

    for(size_t i = 0; i < padded_len; i += 16){
        kuznechik_encrypt(padded + i, encrypted + i);
    }
}

void decrypt_message(const u8 *encrypted, size_t enc_len, char *decrypted) {
    u8 temp[1024];

    for (size_t i = 0; i < enc_len; i += 16) {
        kuznechik_decrypt(encrypted + i, temp + i);
    }

    size_t pad_len = temp[enc_len - 1];

    if (pad_len > 0 && pad_len <= 16 && pad_len < enc_len) {
        memcpy(decrypted, temp, enc_len - pad_len);
        decrypted[enc_len - pad_len] = '\0';

    } else {
        memcpy(decrypted, temp, enc_len);
        decrypted[enc_len] = '\0';
    }
}
