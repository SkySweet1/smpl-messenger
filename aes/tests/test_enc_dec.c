static const u8 Rcon[11] = {0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36};

static u8 round_keys[176];

static u8 xtime(u8 x){
    return (x << 1) ^ ((x >> 7) * 0x1b);
}

static u8 gmul(u8 a, u8 b){
    u8 p = 0;

    for(int i = 0; i < 8; i++){
        if(b & 1){
            p ^= a;
        }

        u8 hi = a & 0x80;

        a<<=1;

        if(hi){
            a ^= 0x1b;
        }

        b >>= 1;
    }

    return p;
}

void aes_init(const u8 *key){
    memcpy(round_keys, key, 16);

    for(int i = 16; i < 176; i += 4){
        u8 t[4];

        memcpy(t, round_keys + i - 4, 4);

        if(i % 16 == 0){
            u8 tmp = t[0];

            t[0] = sbox[t[1]] ^ Rcon[i / 16];
            t[1] = sbox[t[2]];
            t[2] = sbox[t[3]];
            t[3] = sbox[tmp];
        }

        for(int j = 0; j < 4; j++){
            round_keys[i + j] = round_keys[i - 16 + j] ^ t[j];
        }
    }
}

static void add_round_key(u8 *s, int r){
    for(int i = 0; i < 16; i++){
        s[i] ^= round_keys[r * 16 + i];
    }
}

static void sub_bytes(u8 *s){
    for(int i = 0; i < 16; i++){
        s[i] = sbox[s[i]];
    }
}

static void inv_sub_bytes(u8 *s){
    for(int i = 0; i < 16; i++){
        s[i] = inv_sbox[s[i]];
    }
}

static void shift_rows(u8 *s){
    u8 t;

    t = s[1];  s[1]  = s[5];  s[5]  = s[9];  s[9]  = s[13]; s[13] = t;
    t = s[2];  s[2]  = s[10];                               s[10] = t;
    t = s[6];  s[6]  = s[14];                               s[14] = t;
    t = s[15]; s[15] = s[11]; s[11] = s[7];  s[7]  = s[3];  s[3]  = t;
    
}

static void inv_shift_rows(u8 *s){
    u8 t;

    t = s[13]; s[13] = s[9];  s[9]  = s[5];  s[5]  = s[1];  s[1]  = t;
    t = s[2];  s[2]  = s[10];                               s[10] = t;
    t = s[6];  s[6]  = s[14];                               s[14] = t;
    t = s[3];  s[3]  = s[7];  s[7]  = s[11]; s[11] = s[15]; s[15] = t;
}

static void mix_columns(u8 *s){
    for(int c = 0; c < 4; c++){
        u8 *col = s + 4 * c;

        u8 a0 = col[0], a1 = col[1], a2 = col[2], a3 = col[3];

        col[0] = xtime(a0) ^ (xtime(a1) ^ a1) ^ a2 ^ a3;
        col[1] = a0 ^ xtime(a1) ^ (xtime(a2) ^ a2) ^ a3;
        col[2] = a0 ^ a1 ^ xtime(a2) ^ (xtime(a3) ^ a3);
        col[3] = (xtime(a0) ^ a0) ^ a1 ^ a2 ^ xtime(a3);
    }
}

static void inv_mix_columns(u8 *s){
    for(int c = 0; c < 4; c++){
        u8 *col = s + 4 * c;

        u8 a0=col[0], a1=col[1], a2=col[2], a3=col[3];

        col[0] = gmul(a0,14) ^ gmul(a1,11) ^ gmul(a2,13) ^ gmul(a3,9);
        col[1] = gmul(a0,9)  ^ gmul(a1,14) ^ gmul(a2,11) ^ gmul(a3,13);
        col[2] = gmul(a0,13) ^ gmul(a1,9)  ^ gmul(a2,14) ^ gmul(a3,11);
        col[3] = gmul(a0,11) ^ gmul(a1,13) ^ gmul(a2,9)  ^ gmul(a3,14);
    }
}

void aes_encrypt_block(const u8 *plain, u8 *cipher){
    u8 s[16];

    memcpy(s, plain, 16);
    add_round_key(s, 0);

    for(int r = 1; r < 10; r++){
        sub_bytes(s);
        shift_rows(s);
        mix_columns(s);
        add_round_key(s, r);
    }

    sub_bytes(s);
    shift_rows(s);
    add_round_key(s, 10);
    memcpy(cipher, s, 16);
}

void aes_decrypt_block(const u8 *cipher, u8 *plain){
    u8 s[16];

    memcpy(s, cipher, 16);
    add_round_key(s, 10);

    for(int r = 9; r > 0; r--){
        inv_shift_rows(s);
        inv_sub_bytes(s);
        add_round_key(s, r);
        inv_mix_columns(s);
    }

    inv_shift_rows(s);
    inv_sub_bytes(s);
    add_round_key(s, 0);
    memcpy(plain, s, 16);
}

void aes_encrypt_message(const char *msg, u8 *encrypted, size_t *enc_len){
    size_t msg_len = strlen(msg);                   // длина исходного сообщения
    u8 padded[1024];                                // временный буфер для сообщения с PKCS#7 дополнением
    memcpy(padded, msg, msg_len);

        
    size_t pad_len = 16 - (msg_len % 16);           // длина дополнения по PKCS#7

    memset(padded + msg_len, pad_len, pad_len);     // добавляем дополнение в конец сообщения
    *enc_len = msg_len + pad_len;                   // итоговая длина зашифрованного сообщения (кратна 16)

    for(size_t i = 0; i < *enc_len; i += 16){
        aes_encrypt_block(padded + i, encrypted + i);
    }

}

void aes_decrypt_message(const u8 *encrypted, size_t enc_len, char *decrypted){
    u8 temp[1024];

    for(size_t i = 0; i < enc_len; i += 16){
        aes_decrypt_block(encrypted + i, temp + i);
    }

    size_t pad_len = temp[enc_len - 1];

    if(pad_len >= 1 && pad_len <= 16 && pad_len <= enc_len){
        memcpy(decrypted, temp, enc_len - pad_len);
        decrypted[enc_len - pad_len] = '\0';
    } else {
        memcpy(decrypted, temp, enc_len);
        decrypted[enc_len] = '\0';
    }
}
