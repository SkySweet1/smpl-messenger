int bigint_get_bit(const bigint_t *number, int bits){
    int word = bits / 32;
    int position = bits % 32;

    if(word >= number->length){
        return 0;
    }

    return (number->limbs[word] >> position) & 1;
}
/*
функция достает значение конкретного бита 0 или 1 из огромного числа по его порядкового номера

word = bits / 32
    так как число храниться в виде массива 32-х битных слов то нужно делить индекс нужного бита на 32
    и word как раз хранит в каком именно слове (ячейке массива) находиться этот байт

powition = bits % 32
    остаток от деления на 32 показвает на какой именно позиции этого слова находиться этот байт

if(word >= number->length){return 0;}
    проверка на выход за границы
    если просить бит который находиться дальше чем реальная длинна числа - значит запрашиваем старший бит
    по умолчанию всегда ноль

return (number->limbs[word] >> position) & 1;
    берем нужное слово из памяти
    сдвигаем вправо на position раз
    делаем побитовое и (& 1) чтобы оставить только правый бит и все остальное стереть в ноль
    возвращаем в результат

в RSA в алгоритме возведени в степерь по модулю нужно перебиьрать биты показателя стапени от младшего к старшему 
эта функция позволяет узнать равна ли текущая позиция еденице или нулю
*/

void bigint_print_hex(const bigint_t *number){
    if(number->length == 0){
        printf("0\n");

        return;
    }

    printf("0x%X", number->limbs[number->length - 1]);

    for(int i = number->length - 2; i >= 0; i--){
        printf("%08X", number->limbs[i]);
    }

    printf("\n");
}
